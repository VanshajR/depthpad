//! Scan code set 1 (Raw Input / hook scan code, E0 prefix as 0xE000) -> HID keyboard usage.

pub fn to_hid(code: u16) -> Option<u16> {
    let plain = match code {
        0x01 => 41, 0x02 => 30, 0x03 => 31, 0x04 => 32, 0x05 => 33, 0x06 => 34, 0x07 => 35, 0x08 => 36,
        0x09 => 37, 0x0A => 38, 0x0B => 39, 0x0C => 45, 0x0D => 46, 0x0E => 42, 0x0F => 43, 0x10 => 20,
        0x11 => 26, 0x12 => 8, 0x13 => 21, 0x14 => 23, 0x15 => 28, 0x16 => 24, 0x17 => 12, 0x18 => 18,
        0x19 => 19, 0x1A => 47, 0x1B => 48, 0x1C => 40, 0x1D => 224, 0x1E => 4, 0x1F => 22, 0x20 => 7,
        0x21 => 9, 0x22 => 10, 0x23 => 11, 0x24 => 13, 0x25 => 14, 0x26 => 15, 0x27 => 51, 0x28 => 52,
        0x29 => 53, 0x2A => 225, 0x2B => 49, 0x2C => 29, 0x2D => 27, 0x2E => 6, 0x2F => 25, 0x30 => 5,
        0x31 => 17, 0x32 => 16, 0x33 => 54, 0x34 => 55, 0x35 => 56, 0x36 => 229, 0x38 => 226, 0x39 => 44,
        0x3A => 57,
        // E0-prefixed
        0xE01D => 228, 0xE038 => 230, 0xE05B => 227, 0xE05C => 231, 0xE047 => 74, 0xE048 => 82,
        0xE049 => 75, 0xE04B => 80, 0xE04D => 79, 0xE04F => 77, 0xE050 => 81, 0xE051 => 78, 0xE052 => 73,
        0xE053 => 76,
        _ => return None, // includes the E0 2A / E0 36 fake shifts
    };
    Some(plain)
}

pub fn code(scan: u16, extended: bool) -> u16 {
    (scan & 0xFF) | if extended { 0xE000 } else { 0 }
}
